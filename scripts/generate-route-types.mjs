#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname } from 'node:path';

const manifestPath = 'crates/gate-server/src/route_manifest.rs';
const outPath = 'web/src/lib/api/route-manifest.ts';
const check = process.argv.includes('--check');

const source = readFileSync(manifestPath, 'utf8');
const modeMap = {
  ALL_HTTP: ['all', 'gateway', 'controlplane'],
  DATA_PLANE: ['all', 'gateway'],
  CONTROL_PLANE: ['all', 'controlplane'],
};

const routeMacroBlocks = [...source.matchAll(/route!\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*([A-Za-z0-9_]+)\s*,\s*([A-Z_]+)\s*\)/g)];
const routeStructBlocks = [...source.matchAll(/RouteMeta\s*\{([\s\S]*?)\},/g)].map((block) => block[1]);
const rawRoutes = routeMacroBlocks.length
  ? routeMacroBlocks.map((m) => ({ method: m[1], path: m[2], authRaw: m[3], modeRaw: m[4], raw: m[0] }))
  : routeStructBlocks.map((text) => ({
      method: text.match(/method:\s*"([^"]+)"/)?.[1],
      path: text.match(/path:\s*"([^"]+)"/)?.[1],
      authRaw: text.match(/auth:\s*AuthClass::([A-Za-z0-9_]+)/)?.[1],
      modeRaw: text.match(/modes:\s*([A-Z_]+)/)?.[1],
      raw: text,
    }));

const routes = rawRoutes.map(({ method, path, authRaw, modeRaw, raw }) => {
  if (!method || !path || !authRaw || !modeRaw || !modeMap[modeRaw]) {
    throw new Error(`malformed RouteMeta in ${manifestPath}: ${raw}`);
  }
  const auth = authRaw.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
  return { method, path, auth, modes: modeMap[modeRaw] };
});

routes.sort((a, b) => `${a.path} ${a.method}`.localeCompare(`${b.path} ${b.method}`));

const routeLines = routes
  .map((route) => `\t${JSON.stringify(route)}`)
  .join(',\n');
const content = `// AUTO-GENERATED by scripts/generate-route-types.mjs. Do not edit by hand.\n\nexport const routeManifest = {\n\tschema_version: 1,\n\troutes: [\n${routeLines}\n\t]\n} as const;\n\nexport type RuntimeMode = (typeof routeManifest.routes)[number]['modes'][number];\nexport type RouteMethod = (typeof routeManifest.routes)[number]['method'];\nexport type RoutePath = (typeof routeManifest.routes)[number]['path'];\nexport type RouteAuthClass = (typeof routeManifest.routes)[number]['auth'];\nexport type RouteKey = \`\${RouteMethod} \${RoutePath}\`;\n\nexport const routeKeys = routeManifest.routes.map((route) => \`${'${route.method}'} ${'${route.path}'}\`) as RouteKey[];\n\nexport function hasRoute(method: RouteMethod, path: RoutePath): boolean {\n\treturn routeManifest.routes.some((route) => route.method === method && route.path === path);\n}\n`;

if (check) {
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  if (current !== content) {
    console.error(`${outPath} is out of date; run node scripts/generate-route-types.mjs`);
    process.exit(1);
  }
  console.log(`route types ok: ${routes.length} routes`);
} else {
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, content);
  console.log(`generated ${outPath} (${routes.length} routes)`);
}
